        if ccols0 and "open_rename" not in ccols0:
            self._conn.execute("ALTER TABLE clubs ADD COLUMN open_rename INTEGER NOT NULL DEFAULT 0")
            self._conn.commit()
        # Club emblem: the badge the owner picked for the club (NULL = default).
        ccols = {r["name"] for r in self._conn.execute("PRAGMA table_info(clubs)").fetchall()}
        if ccols and "emblem" not in ccols:
            self._conn.execute("ALTER TABLE clubs ADD COLUMN emblem TEXT")
            self._conn.commit()
        # Email + password login: a salted PBKDF2 hash (NULL until the user sets
        # one). Lets returning players log in on a new device without the magic
        # link (which some in-app browsers cannot open).
        if "password_hash" not in cols:
            self._conn.execute("ALTER TABLE users ADD COLUMN password_hash TEXT")
            self._conn.commit()
        # Victory popups now cover every earned reward, not just buzzer skins.
        # Existing accounts would get a stack of them for things they earned long
        # ago, so the first payload after this migration silently claims whatever
        # is already unlocked and flips this flag; only NEW unlocks pop.
        if "rewards_seeded" not in cols:
            self._conn.execute("ALTER TABLE users ADD COLUMN rewards_seeded INTEGER NOT NULL DEFAULT 0")
            self._conn.commit()
        # Preset artwork changed. v10: opnieuw uitgesneden op de FIGUREN in
        # plaats van op een raster van 3x3. De bronvellen zijn 3x3, maar de
        # figuren zijn er niet binnen getekend: piratenhoeden, kronen,
        # vikinghorens en tovenaarspunten steken boven de denkbeeldige
        # rasterlijn uit. Een strak raster sneed daar dwars doorheen, en dat is
        # waarom sommige avatars bovenaan afgeknipt stonden. Nu wordt elke
        # figuur als aaneengesloten vlek in het alfakanaal opgezocht en is zijn
        # eigen doos de uitsnede. De kadrering en de achtergrondverlopen zijn
        # ongewijzigd, dus alleen de uitsnede is anders.
        # v10 ververst OOK de premium-avatars: die zijn met hetzelfde raster
