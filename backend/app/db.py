    def daily_streak_of(self, user_id: str) -> int:
        """Consecutive Dagronde days ending today (0 when today is not played)."""
        if not user_id:
            return 0
        from . import daily
        days = set(self.daily_days_of(user_id))
        d = daily.today()
        streak = 0
        while d in days:
            streak += 1
            d = daily.previous_day(d)
        return streak

    def emote_packs_of(self, user_id: Optional[str]) -> set:
        """Emote packs this player may send from: the free one for everyone,
        plus milestones reached, packs bought, and packs handed out.

        An owned_items row unlocks ANY pack, whatever its normal unlock rule is,
        so a manual grant (admin, giveaway, code) works for the earned ones too.
        """
        out = set(FREE_EMOTE_PACKS)
        if not user_id:
            return out  # guests still get the free pack
        owned = self.owned_items_of(user_id)
        out |= {p for p in EMOTE_PACK_UNLOCK if p in owned}
        stats = None
        for pack, (kind, need) in EMOTE_PACK_UNLOCK.items():
            if pack in out:
                continue
            if kind == "coins":
                if pack in owned:
                    out.add(pack)
            elif kind in ("wins", "games"):
                if stats is None:
                    stats = self.stats_of(user_id)
                if stats.get(kind, 0) >= need:
                    out.add(pack)
            elif kind == "daily_streak":
                if self.daily_streak_of(user_id) >= need:
                    out.add(pack)
        return out

