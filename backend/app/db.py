    def buy_buzzer_pack_coins(self, user_id: str) -> str:
        """Spend coins to unlock the country buzzer pack. Returns
        'ok' | 'already' | 'insufficient'."""
        with self._lock:
            rows = self._q("SELECT coins, buzzer_skins FROM users WHERE id=?", (user_id,))
            if not rows:
                return "insufficient"
            if rows[0]["buzzer_skins"]:
                return "already"
            if rows[0]["coins"] < self.BUZZER_PACK_COINS:
                return "insufficient"
            self._exec(
                "UPDATE users SET coins=coins-?, buzzer_skins=1 WHERE id=?",
                (self.BUZZER_PACK_COINS, user_id),
            )
        return "ok"

    def _new_ai_code(self) -> str:
        # Human-friendly, unambiguous alphabet (no O/0/I/1), grouped for reading.
        alpha = "ABCDEFGHJKLMNPQRSTUVWXYZ23456789"
        return "-".join("".join(secrets.choice(alpha) for _ in range(4)) for _ in range(3))

    # Which users column a product unlocks.
    _PRODUCT_COL = {"ai": "ai_unlocked", "avatars": "premium_avatars", "buzzers": "buzzer_skins"}

    def create_ai_code(self, source: str = "admin", product: str = "ai") -> str:
        """Mint a fresh unlock code for `product`, store only its hash, return
        the plain code."""
        product = product if product in self._PRODUCT_COL else "ai"
        with self._lock:
            while True:
                code = self._new_ai_code()
                h = _hash(code)
                exists = self._q("SELECT 1 FROM ai_codes WHERE code_hash=?", (h,))
                if exists:
                    continue
                self._exec(
                    "INSERT INTO ai_codes (code_hash, source, product, created_at) VALUES (?,?,?,?)",
                    (h, source if source in ("admin", "paypal") else "admin", product, time.time()),
                )
                return code

    def redeem_ai_code(self, user_id: str, code: str) -> str:
        """Redeem an unlock code for this account. The code carries which product
        it unlocks (ai | avatars | buzzers). Returns:
        'ok' | 'already' (account already had this product) | 'used' | 'invalid'."""
        code = (code or "").strip().upper().replace(" ", "")
        if not code or not user_id:
            return "invalid"
        h = _hash(code)
        with self._lock:  # non-reentrant lock: query inline, never call get_user()
            urows = self._q("SELECT ai_unlocked, premium_avatars, buzzer_skins FROM users WHERE id=?", (user_id,))
            if not urows:
                return "invalid"
            rows = self._q("SELECT redeemed_by, product FROM ai_codes WHERE code_hash=?", (h,))
            if not rows:
                return "invalid"
            product = rows[0]["product"] or "ai"
            col = self._PRODUCT_COL.get(product, "ai_unlocked")
            if urows[0][col]:
                return "already"
            if rows[0]["redeemed_by"]:
                return "used"
            self._exec(
                "UPDATE ai_codes SET redeemed_by=?, redeemed_at=? WHERE code_hash=? AND redeemed_by IS NULL",
                (user_id, time.time(), h),
            )
            self._exec(f"UPDATE users SET {col}=1 WHERE id=?", (user_id,))
        return "ok"

    def ai_code_stats(self, product: str = "ai") -> dict:
        product = product if product in self._PRODUCT_COL else "ai"
        with self._lock:
            rows = self._q(
                "SELECT COUNT(*) AS total, COALESCE(SUM(redeemed_by IS NOT NULL),0) AS redeemed "
                "FROM ai_codes WHERE product=?",
                (product,),
            )
        r = rows[0]
        return {"total": r["total"], "redeemed": r["redeemed"], "open": r["total"] - r["redeemed"]}

    def get_user_by_token(self, token: str) -> Optional[dict]:
        uid = self.auth(token)
        return self.get_user(uid) if uid else None

    # ---- shop: PayPal purchases (idempotent by order id) --------------------

    def purchase_code(self, order_id: str) -> Optional[str]:
        """The code already issued for this PayPal order, if any (idempotency)."""
        if not order_id:
            return None
        with self._lock:
            rows = self._q("SELECT code FROM purchases WHERE order_id=?", (order_id,))
        return rows[0]["code"] if rows else None

    def fulfil_purchase(
        self, order_id: str, user_id: str, amount: str, currency: str,
        email: Optional[str] = None, product: str = "ai",
    ) -> Optional[str]:
        """Record a captured PayPal order and unlock `product` for the buyer,
        exactly once. Returns the issued unlock code, or None if this order was
        already fulfilled by a concurrent request (caller reads purchase_code())."""
        if not order_id or not user_id:
            return None
        product = product if product in self._PRODUCT_COL else "ai"
        col = self._PRODUCT_COL[product]
        code = self._new_ai_code()
        now = time.time()
        with self._lock:
            # INSERT OR IGNORE on the order id is the idempotency gate: a replayed
            # capture hits the existing row and inserts nothing.
            cur = self._exec(
                "INSERT OR IGNORE INTO purchases (order_id, provider, product, user_id, amount, currency, code, email, created_at) "
                "VALUES (?,?,?,?,?,?,?,?,?)",
                (order_id, "paypal", product, user_id, amount, currency, code, email, now),
            )
            if cur.rowcount == 0:
                return None  # already fulfilled; caller reads purchase_code()
            self._exec(
                "INSERT OR IGNORE INTO ai_codes (code_hash, source, product, created_at, redeemed_by, redeemed_at) VALUES (?,?,?,?,?,?)",
                (_hash(code), "paypal", product, now, user_id, now),
            )
            self._exec(f"UPDATE users SET {col}=1 WHERE id=?", (user_id,))
        return code

    def fulfil_coins(self, order_id: str, user_id: str, amount: str, currency: str, product: str = "coins100") -> Optional[int]:
        """Record a captured coin-bundle purchase and add that bundle's coins,
        exactly once. Returns the new balance, or None if already fulfilled."""
        if not order_id or not user_id:
            return None
        coins = self.COIN_BUNDLES.get(product, self.COINS_PER_PACK)
        now = time.time()
        with self._lock:
            cur = self._exec(
                "INSERT OR IGNORE INTO purchases (order_id, provider, product, user_id, amount, currency, code, email, created_at) "
                "VALUES (?,?,?,?,?,?,?,?,?)",
                (order_id, "paypal", product, user_id, amount, currency, None, None, now),
            )
            if cur.rowcount == 0:
                return None  # already fulfilled
            self._exec("UPDATE users SET coins=coins+? WHERE id=?", (coins, user_id))
            rows = self._q("SELECT coins FROM users WHERE id=?", (user_id,))
        return int(rows[0]["coins"]) if rows else None

    # De combo geeft BEIDE munten, dus hij kan niet door fulfil_coins: die kent
    # maar een kolom. Vandaar een eigen tabel met wat elk product uitkeert.
    BUNDLE_GRANTS = {
        "coins100": (100, 0),
        "coins300": (300, 0),
        "coins500": (500, 0),
        "coins1000": (1000, 0),
        "coins1800": (1800, 0),
        "coins3000": (3000, 0),
        "coins5000": (5000, 0),
        "coins8000": (8000, 0),
        "coins12000": (12000, 0),
        "cash100": (0, 100),
        "cash250": (0, 250),
        "cash600": (0, 600),
        "cash1200": (0, 1200),
        "cash2000": (0, 2000),
        "cash3500": (0, 3500),
        "cash5500": (0, 5500),
        "cash8000": (0, 8000),
        "cash12000": (0, 12000),
    }

    def fulfil_bundle(self, order_id: str, user_id: str, amount: str, currency: str, product: str) -> Optional[dict]:
        """Een gekochte bundel eenmalig uitkeren. Geeft de nieuwe saldi terug, of
        None als deze bestelling al afgehandeld was."""
        if not order_id or not user_id:
            return None
        coins, cash = self.BUNDLE_GRANTS.get(product, (0, 0))
        if not coins and not cash:
            return None
        now = time.time()
        with self._lock:
            cur = self._exec(
                "INSERT OR IGNORE INTO purchases (order_id, provider, product, user_id, amount, currency, code, email, created_at) "
                "VALUES (?,?,?,?,?,?,?,?,?)",
                (order_id, "paypal", product, user_id, amount, currency, None, None, now),
            )
            if cur.rowcount == 0:
                return None
            if coins:
                self._exec("UPDATE users SET coins=coins+? WHERE id=?", (coins, user_id))
            if cash:
                self._exec("UPDATE users SET cash=cash+? WHERE id=?", (cash, user_id))
            rows = self._q("SELECT coins, cash FROM users WHERE id=?", (user_id,))
        return {"coins": int(rows[0]["coins"]), "cash": int(rows[0]["cash"])} if rows else None

    # ---- Ontdekken ----------------------------------------------------------
    # Read-only kant van de verzameling. De catalogus is voor iedereen gelijk en
    # verandert alleen via het seed-script, dus die kant is puur SELECT.
    #
    # Elke query die kaarten teruggeeft filtert zelf wat een speler mag zien.
    # Het woord en de facts van een kaart die hij nog niet heeft, verlaten deze
    # laag niet: dat is de hele spanning van de modus, en één vergeten filter in
    # main.py zou hem weggeven. Daarom zit de afscherming hier en niet daar.

    def discover_totals(self) -> dict[str, int]:
        """Aantal kaarten per categorie in de catalogus."""
        rows = self._q("SELECT category, COUNT(*) AS n FROM cards GROUP BY category")
        return {r["category"]: int(r["n"]) for r in rows}

    def discover_owned_counts(self, user_id: str) -> dict[str, int]:
        """Aantal ontdekte kaarten per categorie voor deze speler."""
        rows = self._q(
            "SELECT c.category AS category, COUNT(*) AS n"
            " FROM user_cards uc JOIN cards c ON c.id = uc.card_id"
            " WHERE uc.user_id = ? GROUP BY c.category",
            (user_id,),
        )
        return {r["category"]: int(r["n"]) for r in rows}

    def discover_letters(self, category: str, user_id: Optional[str]) -> list[dict]:
        """Per letter hoeveel kaarten er zijn en hoeveel de speler er heeft.

        Letters zonder kaarten komen NIET terug; de frontend tekent het raster
        van A tot Z en vult aan met nul, want welke letters leeg zijn hoort bij
        de layout en niet bij de data.
        """
        rows = self._q(
            "SELECT c.letter AS letter, COUNT(*) AS total,"
            "       COUNT(uc.id) AS discovered"
            " FROM cards c"
            " LEFT JOIN user_cards uc ON uc.card_id = c.id AND uc.user_id = ?"
            " WHERE c.category = ?"
            " GROUP BY c.letter ORDER BY c.letter",
            (user_id or "", category),
        )
        return [
            {"letter": r["letter"], "total": int(r["total"]), "discovered": int(r["discovered"])}
            for r in rows
        ]

    def discover_cards_for_letter(
        self, category: str, letter: str, user_id: Optional[str]
    ) -> list[dict]:
        """De kaarten van één letter, afgeschermd.

        Een kaart die de speler niet heeft geeft alleen id, card_number en
        discovered=False terug. Geen word, geen facts, geen slug en geen
        image_path: uit elk daarvan is het antwoord af te leiden.
        """
        rows = self._q(
            "SELECT c.id, c.word, c.slug, c.facts, c.image_path, c.card_number, c.iso,"
            "       uc.id AS owned, uc.favorite, uc.discovered_at"
            " FROM cards c"
            " LEFT JOIN user_cards uc ON uc.card_id = c.id AND uc.user_id = ?"
            " WHERE c.category = ? AND c.letter = ?"
            " ORDER BY c.sort_order",
            (user_id or "", category, letter),
        )
        out = []
        for r in rows:
            if r["owned"] is None:
                out.append({
                    "id": int(r["id"]),
                    "card_number": int(r["card_number"]),
                    "discovered": False,
                })
                continue
            out.append({
                "id": int(r["id"]),
                "card_number": int(r["card_number"]),
                "discovered": True,
                "word": r["word"],
                "slug": r["slug"],
                "iso": r["iso"],
                "facts": json.loads(r["facts"] or "{}"),
                "image_path": r["image_path"],
                "favorite": bool(r["favorite"]),
                "discovered_at": r["discovered_at"],
            })
        return out

    def discover_card(self, card_id: int, user_id: Optional[str]) -> Optional[dict]:
        """Eén volledige kaart, of None als de speler hem niet heeft.

        None betekent hier bewust zowel "bestaat niet" als "niet van jou": een
        apart antwoord voor die twee zou verklappen welke kaartnummers bestaan.
        """
        rows = self._q(
            "SELECT c.id, c.category, c.letter, c.word, c.slug, c.facts, c.image_path, c.iso,"
            "       c.card_number, uc.favorite, uc.discovered_at, uc.box, uc.correct_count,"
            "       uc.missed_count"
            " FROM cards c JOIN user_cards uc ON uc.card_id = c.id AND uc.user_id = ?"
            " WHERE c.id = ?",
            (user_id or "", card_id),
        )
        if not rows:
            return None
        r = rows[0]
        return {
            "id": int(r["id"]),
            "category": r["category"],
            "letter": r["letter"],
            "card_number": int(r["card_number"]),
            "discovered": True,
            "word": r["word"],
            "slug": r["slug"],
            "iso": r["iso"],
            "facts": json.loads(r["facts"] or "{}"),
            "image_path": r["image_path"],
            "favorite": bool(r["favorite"]),
            "discovered_at": r["discovered_at"],
            "box": int(r["box"]),
            "correct_count": int(r["correct_count"]),
            "missed_count": int(r["missed_count"]),
        }

    def discover_due_count(self, user_id: str, now: Optional[float] = None) -> int:
        """Hoeveel kaarten klaarstaan om te herhalen."""
        rows = self._q(
            "SELECT COUNT(*) AS n FROM user_cards"
            " WHERE user_id = ? AND next_review_at IS NOT NULL AND next_review_at <= ?",
            (user_id, now if now is not None else time.time()),
        )
        return int(rows[0]["n"]) if rows else 0

    def discover_card_index(self, category: str) -> dict[str, int]:
        """Genormaliseerde vorm -> card_id, voor één categorie.

        De aliassen staan als JSON in de rij, dus dit kan niet in SQL. Dat mag:
        een categorie is een paar honderd rijen en dit draait alleen aan het
        eind van een ronde.
        """
        index: dict[str, int] = {}
        for r in self._q("SELECT id, slug, aliases FROM cards WHERE category=?", (category,)):
            cid = int(r["id"])
            index[r["slug"]] = cid
            # Slug is de genormaliseerde vorm zonder spaties, de aliassen staan
            # er wel mee. Allebei opnemen, want een antwoord kan op beide lijken.
            index.setdefault(r["slug"].replace("-", ""), cid)
            for a in json.loads(r["aliases"] or "[]"):
                index.setdefault(a, cid)
                index.setdefault(a.replace(" ", ""), cid)
        return index

    def discover_owned_card_ids(self, user_id: str, category: str) -> set[int]:
        """De card_ids die deze speler al heeft in één categorie."""
        if not user_id:
            return set()
        return {
            int(r["card_id"])
            for r in self._q(
                "SELECT uc.card_id FROM user_cards uc JOIN cards c ON c.id = uc.card_id"
                " WHERE uc.user_id = ? AND c.category = ?",
                (user_id, category),
            )
        }

    def discover_unlock(
        self,
        user_id: str,
        category: str,
        norms: list[str],
        source: str = "practice",
        known: frozenset[str] = frozenset(),
        now: Optional[float] = None,
    ) -> list[dict]:
        """Ken kaarten toe voor de woorden van een ronde, geef de NIEUWE terug.

        `norms` is al gefilterd door discover.match_words, dus alles hier hoort
        echt bij deze categorie en letter. `known` zijn de woorden die de speler
        zelf noemde; de rest kreeg hij na afloop te zien. Dat verschil bepaalt
        alleen correct_count en missed_count, niet of hij de kaart krijgt: ook
        een woord dat je net leerde is een kaart, dat is de hele modus.

        Alles onder één slot, zodat twee keer op verzenden tikken niet twee keer
        telt. De UNIQUE op (user_id, card_id) doet de rest.
        """
        if not user_id or not norms:
            return []
        ts = now if now is not None else time.time()
        index = self.discover_card_index(category)
        wanted: list[tuple[int, bool]] = []
        seen_ids: set[int] = set()
        for n in norms:
            cid = index.get(n) or index.get(n.replace(" ", ""))
            if cid is None or cid in seen_ids:
                continue
            seen_ids.add(cid)
            wanted.append((cid, n in known))
        if not wanted:
            return []
        fresh: list[int] = []
        with self._lock:
            have = {
                int(r["card_id"])
                for r in self._q(
                    "SELECT card_id FROM user_cards WHERE user_id=? AND card_id IN (%s)"
                    % ",".join("?" * len(wanted)),
                    (user_id, *[c for c, _ in wanted]),
                )
            }
            for cid, was_known in wanted:
                if cid in have:
                    # Al in de verzameling: alleen de teller bijwerken. Box en
                    # next_review_at blijven van de herhaling (fase 5), die
                    # horen niet bij het opnieuw tegenkomen van een woord.
                    col = "correct_count" if was_known else "missed_count"
                    self._exec(
                        f"UPDATE user_cards SET {col}={col}+1 WHERE user_id=? AND card_id=?",
                        (user_id, cid),
                    )
                    continue
                try:
                    self._exec(
                        "INSERT INTO user_cards (user_id, card_id, discovered_at, source,"
                        " correct_count, missed_count, box) VALUES (?,?,?,?,?,?,1)",
                        (user_id, cid, ts, source, 1 if was_known else 0, 0 if was_known else 1),
                    )
                except sqlite3.IntegrityError:
                    continue  # race met een tweede tik, de ander was eerst
                fresh.append(cid)
        return [c for c in (self.discover_card(cid, user_id) for cid in fresh) if c]

    def discover_state(self, user_id: str) -> dict:
        """De dagletter-/streakrij van deze speler, met nullen als hij er nog geen heeft."""
        rows = self._q("SELECT * FROM user_discover_state WHERE user_id = ?", (user_id,))
        if not rows:
            return {
                "daily_letter": None, "daily_letter_date": None,
                "streak_days": 0, "last_played_date": None,
            }
        r = rows[0]
        return {
            "daily_letter": r["daily_letter"],
            "daily_letter_date": r["daily_letter_date"],
            "streak_days": int(r["streak_days"]),
            "last_played_date": r["last_played_date"],
        }


