/** Alle woorden, in hoofdletters, drie letters of langer. */
export const NL_WOORDEN: ReadonlySet<string> = new Set(
  RUW.split(/\s+/).map((w) => w.trim().toUpperCase()).filter((w) => w.length >= 3)
);

/** Per lengte, voor de bordgenerator: die legt woorden van een bepaalde maat. */
export const NL_PER_LENGTE: ReadonlyMap<number, string[]> = (() => {
  const m = new Map<number, string[]>();
  for (const w of NL_WOORDEN) {
    const lijst = m.get(w.length);
    if (lijst) lijst.push(w);
    else m.set(w.length, [w]);
  }
  // Vaste volgorde, zodat een seed morgen hetzelfde bord geeft als vandaag.
  for (const lijst of m.values()) lijst.sort();
  return m;
})();

export const bestaat = (woord: string) => NL_WOORDEN.has(woord.toUpperCase());
