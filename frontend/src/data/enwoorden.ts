/** All words, uppercase, three letters or longer. */
export const EN_WOORDEN: ReadonlySet<string> = new Set(
  RUW.split(/\s+/).map((w) => w.trim().toUpperCase()).filter((w) => w.length >= 3)
);

/** Per length, for the board generator: it plants words of a given size. */
export const EN_PER_LENGTE: ReadonlyMap<number, string[]> = (() => {
  const m = new Map<number, string[]>();
  for (const w of EN_WOORDEN) {
    const lijst = m.get(w.length);
    if (lijst) lijst.push(w);
    else m.set(w.length, [w]);
  }
  // Vaste volgorde, zodat een seed morgen hetzelfde bord geeft als vandaag.
  for (const lijst of m.values()) lijst.sort();
  return m;
})();

/** Elk beginstuk van elk woord, voor de snoei in de oplosser. Zie de toelichting
 *  bij NL_PREFIX: zonder deze set loopt een volledige zoektocht over zestien
 *  vakjes in de miljoenen paden. */
export const EN_PREFIX: ReadonlySet<string> = (() => {
  const s = new Set<string>();
  for (const w of EN_WOORDEN) for (let i = 1; i <= w.length; i++) s.add(w.slice(0, i));
  return s;
})();

export const EN_MAX_LENGTE = Math.max(...[...EN_WOORDEN].map((w) => w.length));
